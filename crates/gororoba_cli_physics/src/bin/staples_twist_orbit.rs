//! Invariant-matched nonassociative twist ensemble and algebra-isomorphic
//! relabeling orbit against the sedenion associator on the staples benchmark.
//!
//! Evaluates three control/orbit families against the canonical Cayley-Dickson
//! sedenion associator on the THEMIS-A Staples benchmark subsample:
//!
//! 1. Normalized-cocycle family (negative control):
//!    Normalized 2-cocycles on (Z_2)^4 defining associative twisted group algebras.
//!    Because they are 2-cocycles, the associator vanishes identically (0 terms),
//!    producing chance-level discrimination (AUC = 0.5000).
//!
//! 2. Basis-alternative 35-line twist ensemble:
//!    Twists matching the algebraic axioms of the Cayley-Dickson sedenion basis:
//!    unital (sigma(0,.) = sigma(.,0) = +1), imaginary squares (sigma(i,i) = -1 for i >= 1),
//!    anticommutative (sigma(i,j) = -sigma(j,i) for i != j >= 1), and basis alternative
//!    ([e_i, e_i, e_j] = 0, meaning each of the 35 lines of PG(3, 2) is a quaternion triad).
//!    The orientations of the 35 lines are sampled uniformly over the 2^35 such twists.
//!    Support is not matched to the canonical 1848-term tensor: random draws concentrate
//!    on 1080..1656 balanced terms. The Cayley-Dickson orientation is the 1848-term point
//!    recovered by extract_line_orientations.
//!
//! 3. Algebra-isomorphic relabeling orbit:
//!    Twists sigma_{pi, s}(i, j) = s_i s_j s_{i ^ j} sigma_0(pi(i), pi(j)) generated by
//!    linear automorphisms pi in GL(4, Z_2) and sign vectors s in {+1, -1}^16 (s[0]=+1).
//!    Every draw defines an algebra strictly isomorphic to the Cayley-Dickson sedenions,
//!    with identically 1848 terms (924 positive, 924 negative). This evaluates the sensitivity
//!    of the physical detector to the coordinate alignment of the sedenion basis.

use anyhow::{Context, Result};
use cd_kernel::mult_table::CdMultTable;
use clap::Parser;
use gororoba_cli_physics::staple_associator::{
    STAPLE_DIM, joint_associator_norms, staple_embedding,
};
use gororoba_cli_physics::staple_benchmark::{
    load_labeled_files, percentile, rank_auc, stratified_keep,
};
use gororoba_cli_physics::staple_controls::{
    EnsembleIntervalPosition, SparseCubicTensor, cd_twist, ensemble_interval_position, pg32_lines,
    random_alternative_twist, random_isomorphic_twist, random_normalized_cocycle, twist_sha256,
};
use rand::SeedableRng;
use rand_chacha::ChaCha8Rng;
use rayon::prelude::*;
use serde::Serialize;
use std::{fs, path::PathBuf, time::Instant};

#[derive(Parser, Debug)]
#[command(
    about = "Invariant-matched twist ensemble, isomorphic relabeling orbit, and cocycle negative control"
)]
struct Args {
    /// CSV with a `path` column listing daily THEMIS-A FGM files.
    #[arg(long, default_value = "data/output/tha_matched_files.csv")]
    matched_files: PathBuf,
    /// Crossing catalog CSV with a `TIMESTAMP` column (Staples et al. 2020).
    #[arg(long, default_value = "data/output/cat_themis_a.csv")]
    catalog: PathBuf,
    /// Output JSON.
    #[arg(long, default_value = "data/output/staples_twist_orbit.json")]
    out: PathBuf,
    /// Number of normalized 2-cocycle negative controls.
    #[arg(long, default_value_t = 50)]
    n_cocycles: usize,
    /// Number of uniform 35-line basis-alternative twists.
    #[arg(long, default_value_t = 250)]
    n_invariant_twists: usize,
    /// Number of draws from the algebra-isomorphic relabeling orbit.
    #[arg(long, default_value_t = 250)]
    n_isomorphic_orbits: usize,
    #[arg(long, default_value_t = 42)]
    seed: u64,
    /// Fraction of negatives kept per file; every positive is kept.
    #[arg(long, default_value_t = 0.05)]
    neg_fraction: f64,
    #[arg(long, default_value_t = 2.0)]
    label_pad_minutes: f64,
    #[arg(long, default_value_t = 500)]
    min_samples: usize,
}

struct PrecomputedTriple {
    a: [f64; STAPLE_DIM],
    b: [f64; STAPLE_DIM],
    c: [f64; STAPLE_DIM],
    inv_denom: f64,
}

#[derive(Serialize)]
struct DrawRecord {
    index: usize,
    auc: f64,
    term_count: usize,
    positive_terms: usize,
    negative_terms: usize,
    twist_sha256: String,
}

#[derive(Serialize)]
struct EnsembleSummary {
    n: usize,
    mean: f64,
    std: f64,
    min: f64,
    p2_5: f64,
    p50: f64,
    p97_5: f64,
    max: f64,
    /// (1 + #{draw AUC >= canonical AUC}) / (n + 1)
    tail_probability_ge_canonical: f64,
    draws_at_or_above_canonical: usize,
    term_count_min: usize,
    term_count_max: usize,
}

#[derive(Serialize)]
struct Output {
    preregistration: Preregistration,
    sample: SampleRecord,
    canonical: CanonicalRecord,
    normalized_cocycles: EnsembleSummary,
    invariant_matched_twists: EnsembleSummary,
    isomorphic_orbit: EnsembleSummary,
    cocycle_draws: Vec<DrawRecord>,
    invariant_twist_draws: Vec<DrawRecord>,
    isomorphic_orbit_draws: Vec<DrawRecord>,
    decisions: DecisionsRecord,
    elapsed_seconds: f64,
}

#[derive(Serialize)]
struct Preregistration {
    hypothesis: &'static str,
    control_family_cocycle: &'static str,
    control_family_invariant_twist: &'static str,
    orbit_family_isomorphic: &'static str,
    falsifiers: Vec<&'static str>,
    seed_policy: String,
    n_cocycles: usize,
    n_invariant_twists: usize,
    n_isomorphic_orbits: usize,
    neg_fraction: f64,
    label_pad_minutes: f64,
    min_samples: usize,
}

#[derive(Serialize)]
struct SampleRecord {
    files: usize,
    full_samples: usize,
    full_positives: usize,
    subsample_size: usize,
    subsample_positives: usize,
}

#[derive(Serialize)]
struct CanonicalRecord {
    full_sample_auc: f64,
    subsample_auc: f64,
    term_count: usize,
    positive_terms: usize,
    negative_terms: usize,
    twist_sha256: String,
    from_twist_reproduces_from_associator: bool,
}

#[derive(Serialize)]
struct DecisionsRecord {
    cocycle_negative_control: String,
    invariant_twist_ensemble: String,
    isomorphic_relabeling_orbit: String,
    overall_verdict: String,
}

fn summarize(draws: &[DrawRecord], canonical: f64) -> EnsembleSummary {
    let mut sorted: Vec<f64> = draws.iter().map(|d| d.auc).collect();
    sorted.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));
    let n = sorted.len();
    let mean = sorted.iter().sum::<f64>() / n as f64;
    let std =
        (sorted.iter().map(|a| (a - mean).powi(2)).sum::<f64>() / (n as f64 - 1.0).max(1.0)).sqrt();
    let above = sorted.iter().filter(|&&a| a >= canonical).count();
    let term_count_min = draws.iter().map(|d| d.term_count).min().unwrap_or(0);
    let term_count_max = draws.iter().map(|d| d.term_count).max().unwrap_or(0);
    EnsembleSummary {
        n,
        mean,
        std,
        min: sorted[0],
        p2_5: percentile(&sorted, 0.025),
        p50: percentile(&sorted, 0.5),
        p97_5: percentile(&sorted, 0.975),
        max: sorted[n - 1],
        tail_probability_ge_canonical: (1 + above) as f64 / (n + 1) as f64,
        draws_at_or_above_canonical: above,
        term_count_min,
        term_count_max,
    }
}

fn interval_decision(family: &str, canonical_auc: f64, summary: &EnsembleSummary) -> String {
    let position = ensemble_interval_position(canonical_auc, summary.p2_5, summary.p97_5);
    let interval = format!(
        "[{:.4}, {:.4}], terms {}..{}, {} of {} draws >= canonical (tail {:.4})",
        summary.p2_5,
        summary.p97_5,
        summary.term_count_min,
        summary.term_count_max,
        summary.draws_at_or_above_canonical,
        summary.n,
        summary.tail_probability_ge_canonical
    );
    match position {
        EnsembleIntervalPosition::Above => format!(
            "canonical CD exceeds the {family}: canonical AUC {canonical_auc:.4} is above p97.5 {interval}"
        ),
        EnsembleIntervalPosition::Below => format!(
            "canonical CD is below the {family}: canonical AUC {canonical_auc:.4} is below p2.5 {interval}"
        ),
        EnsembleIntervalPosition::Inside => format!(
            "canonical CD sits inside the {family}: canonical AUC {canonical_auc:.4} is inside {interval}"
        ),
    }
}

fn main() -> Result<()> {
    let args = Args::parse();
    let start = Instant::now();
    eprintln!("loading matched files ...");
    let files = load_labeled_files(
        &args.matched_files,
        &args.catalog,
        args.label_pad_minutes,
        args.min_samples,
    )?;
    anyhow::ensure!(!files.is_empty(), "no labeled files");

    let table = CdMultTable::generate(STAPLE_DIM);
    let cd = SparseCubicTensor::from_associator(&table);
    let sigma0 = cd_twist(&table);
    let cd_from_twist = SparseCubicTensor::from_twist(&sigma0);
    let lines = pg32_lines();

    let mut full_scores: Vec<f64> = Vec::new();
    let mut full_labels: Vec<bool> = Vec::new();
    let mut triples: Vec<PrecomputedTriple> = Vec::new();
    let mut sub_labels: Vec<bool> = Vec::new();
    for f in &files {
        let staples = staple_embedding(&f.rows);
        let assoc = joint_associator_norms(&staples, true);
        anyhow::ensure!(
            assoc.len() == f.labels.len(),
            "label alignment in {}",
            f.path
        );
        full_scores.extend_from_slice(&assoc);
        full_labels.extend_from_slice(&f.labels);
        for k in stratified_keep(&f.labels, f.file_id, args.seed, args.neg_fraction) {
            let a = staples[k];
            let b = staples[k + 1];
            let c = staples[k + 2];
            let na = a.iter().map(|x| x * x).sum::<f64>().sqrt();
            let nb = b.iter().map(|x| x * x).sum::<f64>().sqrt();
            let nc = c.iter().map(|x| x * x).sum::<f64>().sqrt();
            let inv_denom = 1.0 / (na * nb * nc + 1e-30);
            triples.push(PrecomputedTriple { a, b, c, inv_denom });
            sub_labels.push(f.labels[k]);
        }
    }
    eprintln!(
        "{} files, {} samples ({} positives), subsample {} ({} positives) in {:.0} s",
        files.len(),
        full_scores.len(),
        full_labels.iter().filter(|&&l| l).count(),
        triples.len(),
        sub_labels.iter().filter(|&&l| l).count(),
        start.elapsed().as_secs_f64()
    );
    let sample = SampleRecord {
        files: files.len(),
        full_samples: full_scores.len(),
        full_positives: full_labels.iter().filter(|&&l| l).count(),
        subsample_size: triples.len(),
        subsample_positives: sub_labels.iter().filter(|&&l| l).count(),
    };
    drop(files);

    let full_sample_auc = rank_auc(&full_scores, &full_labels);
    drop(full_scores);
    drop(full_labels);

    let score = |t: &SparseCubicTensor| -> Vec<f64> {
        if t.term_count() == 0 {
            return vec![0.0; triples.len()];
        }
        triples
            .par_iter()
            .map(|tr| t.score_triple_precomputed(&tr.a, &tr.b, &tr.c, tr.inv_denom))
            .collect()
    };

    let cd_scores = score(&cd);
    let twist_scores = score(&cd_from_twist);
    let reproduces = cd_from_twist.term_count() == cd.term_count()
        && cd_scores
            .iter()
            .zip(&twist_scores)
            .all(|(x, y)| (x - y).abs() <= 1e-12 * x.abs().max(1.0));
    anyhow::ensure!(
        reproduces,
        "from_twist(cd_twist) must reproduce from_associator"
    );
    let canonical_auc = rank_auc(&cd_scores, &sub_labels);
    let (cd_pos, cd_neg) = cd.sign_counts();
    eprintln!(
        "canonical CD AUC: full {:.4}, subsample {:.4} ({} terms)",
        full_sample_auc,
        canonical_auc,
        cd.term_count()
    );

    // Arm 1: Normalized 2-cocycles (Negative Control)
    eprintln!("evaluating {} normalized 2-cocycles ...", args.n_cocycles);
    let mut cocycle_draws = Vec::with_capacity(args.n_cocycles);
    for d in 0..args.n_cocycles {
        let mut rng = ChaCha8Rng::seed_from_u64(
            args.seed
                .wrapping_add((d as u64 + 1).wrapping_mul(0x517C_C1B7_2722_0A95)),
        );
        let sigma = random_normalized_cocycle(&mut rng);
        let t = SparseCubicTensor::from_twist(&sigma);
        anyhow::ensure!(
            t.term_count() == 0,
            "normalized 2-cocycle must have zero associator terms"
        );
        let (pos, neg) = t.sign_counts();
        let scores = score(&t);
        let auc = rank_auc(&scores, &sub_labels);
        cocycle_draws.push(DrawRecord {
            index: d,
            auc,
            term_count: t.term_count(),
            positive_terms: pos,
            negative_terms: neg,
            twist_sha256: twist_sha256(&sigma),
        });
    }

    // Arm 2: Uniform 35-line basis-alternative twist ensemble
    eprintln!(
        "evaluating {} 35-line basis-alternative twists ...",
        args.n_invariant_twists
    );
    let mut invariant_twist_draws = Vec::with_capacity(args.n_invariant_twists);
    for d in 0..args.n_invariant_twists {
        let mut rng = ChaCha8Rng::seed_from_u64(
            args.seed
                .wrapping_add((d as u64 + 1).wrapping_mul(0x9E37_79B9_7F4A_7C15)),
        );
        let sigma = random_alternative_twist(&lines, &mut rng);
        let t = SparseCubicTensor::from_twist(&sigma);
        let (pos, neg) = t.sign_counts();
        let auc = rank_auc(&score(&t), &sub_labels);
        invariant_twist_draws.push(DrawRecord {
            index: d,
            auc,
            term_count: t.term_count(),
            positive_terms: pos,
            negative_terms: neg,
            twist_sha256: twist_sha256(&sigma),
        });
        if (d + 1) % 50 == 0 {
            eprintln!(
                "alternative twist draw {}/{}: auc {:.4}, terms {} ({:.0} s)",
                d + 1,
                args.n_invariant_twists,
                auc,
                t.term_count(),
                start.elapsed().as_secs_f64()
            );
        }
    }

    // Arm 3: Algebra-isomorphic relabeling orbit
    eprintln!(
        "evaluating {} algebra-isomorphic relabeling orbit draws ...",
        args.n_isomorphic_orbits
    );
    let mut isomorphic_orbit_draws = Vec::with_capacity(args.n_isomorphic_orbits);
    for d in 0..args.n_isomorphic_orbits {
        let mut rng = ChaCha8Rng::seed_from_u64(
            args.seed
                .wrapping_add((d as u64 + 10001).wrapping_mul(0x9E37_79B9_7F4A_7C15)),
        );
        let sigma = random_isomorphic_twist(&sigma0, &mut rng);
        let t = SparseCubicTensor::from_twist(&sigma);
        anyhow::ensure!(
            t.term_count() == 1848,
            "isomorphic twist must have 1848 terms"
        );
        let (pos, neg) = t.sign_counts();
        anyhow::ensure!(
            pos == 924 && neg == 924,
            "isomorphic twist must have 924 positive and 924 negative terms"
        );
        let auc = rank_auc(&score(&t), &sub_labels);
        isomorphic_orbit_draws.push(DrawRecord {
            index: d,
            auc,
            term_count: t.term_count(),
            positive_terms: pos,
            negative_terms: neg,
            twist_sha256: twist_sha256(&sigma),
        });
        if (d + 1) % 50 == 0 {
            eprintln!(
                "isomorphic orbit draw {}/{}: auc {:.4}, terms {} ({:.0} s)",
                d + 1,
                args.n_isomorphic_orbits,
                auc,
                t.term_count(),
                start.elapsed().as_secs_f64()
            );
        }
    }

    let normalized_cocycles = summarize(&cocycle_draws, canonical_auc);
    let invariant_matched_twists = summarize(&invariant_twist_draws, canonical_auc);
    let isomorphic_orbit = summarize(&isomorphic_orbit_draws, canonical_auc);

    let cocycle_decision = format!(
        "negative control verified: all {} normalized 2-cocycles have zero associator terms and chance-level AUC {:.4}",
        normalized_cocycles.n, normalized_cocycles.mean
    );

    let invariant_decision = interval_decision(
        "35-line basis-alternative twist ensemble",
        canonical_auc,
        &invariant_matched_twists,
    );
    let iso_decision = interval_decision(
        "algebra-isomorphic relabeling orbit",
        canonical_auc,
        &isomorphic_orbit,
    );

    let overall_verdict = format!(
        "{}; {}; {}",
        cocycle_decision, invariant_decision, iso_decision
    );
    eprintln!("\n=== VERDICTS ===");
    eprintln!("{cocycle_decision}");
    eprintln!("{invariant_decision}");
    eprintln!("{iso_decision}");

    let decisions = DecisionsRecord {
        cocycle_negative_control: cocycle_decision,
        invariant_twist_ensemble: invariant_decision,
        isomorphic_relabeling_orbit: iso_decision,
        overall_verdict,
    };

    let output = Output {
        preregistration: Preregistration {
            hypothesis: "The Cayley-Dickson sedenion associator tensor's benchmark performance is specific relative to (1) the negative-control normalized-cocycle family, (2) the 35-line basis-alternative twist ensemble on PG(3, 2), and (3) its own algebra-isomorphic relabeling orbit under GL(4, Z_2) automorphisms.",
            control_family_cocycle: "n_cocycles normalized 2-cocycles sigma(i,j) = (-1)^{i^T B j} tau(i) tau(j) tau(i ^ j) with B in GF(2)^{4x4}, tau(0)=+1; associator vanishes identically.",
            control_family_invariant_twist: "n_invariant_twists unital, anticommutative, basis-alternative twists with imaginary squares -1, parameterized by fair orientation signs on the 35 projective lines of PG(3, 2). Support is not matched to the canonical 1848-term tensor.",
            orbit_family_isomorphic: "n_isomorphic_orbits draws from the GL(4, Z_2) x (Z_2)^15 algebra-isomorphic relabeling orbit: sigma_{pi, s}(i, j) = s_i s_j s_{i ^ j} sigma_0(pi(i), pi(j)), preserving exact 1848-term support and 924/924 balance.",
            falsifiers: vec![
                "False if any normalized 2-cocycle has non-zero associator terms or non-chance AUC.",
                "False if canonical CD AUC is at or below the 97.5th percentile of the 35-line basis-alternative twist ensemble.",
                "The isomorphic orbit reports the coordinate-relabeling sensitivity of the sedenion associator; specificity fails if canonical AUC is at or below that orbit's 97.5th percentile.",
            ],
            seed_policy: format!(
                "ChaCha8; cocycle d uses seed {} + (d+1)*0x517CC1B727220A95; invariant twist d uses seed {} + (d+1)*0x9E3779B97F4A7C15; isomorphic orbit d uses seed {} + (d+10001)*0x9E3779B97F4A7C15; subsample keeps every positive and each negative with probability {} from ChaCha8(seed XOR file_id*0x9E3779B97F4A7C15)",
                args.seed, args.seed, args.seed, args.neg_fraction
            ),
            n_cocycles: args.n_cocycles,
            n_invariant_twists: args.n_invariant_twists,
            n_isomorphic_orbits: args.n_isomorphic_orbits,
            neg_fraction: args.neg_fraction,
            label_pad_minutes: args.label_pad_minutes,
            min_samples: args.min_samples,
        },
        sample,
        canonical: CanonicalRecord {
            full_sample_auc,
            subsample_auc: canonical_auc,
            term_count: cd.term_count(),
            positive_terms: cd_pos,
            negative_terms: cd_neg,
            twist_sha256: twist_sha256(&sigma0),
            from_twist_reproduces_from_associator: reproduces,
        },
        normalized_cocycles,
        invariant_matched_twists,
        isomorphic_orbit,
        cocycle_draws,
        invariant_twist_draws,
        isomorphic_orbit_draws,
        decisions,
        elapsed_seconds: start.elapsed().as_secs_f64(),
    };

    if let Some(parent) = args.out.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&args.out, serde_json::to_string_pretty(&output)?)
        .with_context(|| format!("write {}", args.out.display()))?;
    eprintln!("wrote {}", args.out.display());
    Ok(())
}
