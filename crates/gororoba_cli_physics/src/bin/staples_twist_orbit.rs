        retained.scores.invariant_twist_draws[0]
            .twist_sha256
            .push('0');
        assert!(verify_retained(&args, &retained).is_err());
        retained.scores.invariant_twist_draws[0].twist_sha256.pop();
        retained.scores.cocycle_draws[0].auc = 0.6;
        assert!(verify_retained(&args, &retained).is_err());
        retained.scores.cocycle_draws[0].auc = 0.5;
        retained.preregistration.neg_fraction = 0.1;
        assert!(verify_retained(&args, &retained).is_err());
