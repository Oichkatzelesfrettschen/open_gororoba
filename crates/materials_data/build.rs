// build.rs -- materials_data codegen
//
// WHY: Storing 17K+ lines of float literals as Rust source inflates rustc's
//      parse + type-check work on every incremental rebuild and makes CPD scans
//      quadratically expensive. This script reads human-readable data files from
//      data/ and emits the matching const arrays into OUT_DIR.
//
// Output files:
//   $OUT_DIR/generated_nk_tables.rs     -- tabulated n,k const arrays (Phase 2)
//   $OUT_DIR/generated_optical_params.rs -- Drude metal const arrays (Phase 3)
//   $OUT_DIR/generated_crystal_tables.rs -- placeholder (Phase 4 / task #58)

use std::{
    env,
    fs::{self, File},
    io::{BufRead, BufReader, Write},
    path::PathBuf,
};

fn main() {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR not set"));
    let data_nk = manifest.join("data").join("nk");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=data/");

    // ---------- Phase 2: tabulated n,k tables ----------
    let nk_out = out_dir.join("generated_nk_tables.rs");
    let mut nk_file = File::create(&nk_out).expect("failed to create generated_nk_tables.rs");

    writeln!(
        nk_file,
        "// Auto-generated by materials_data/build.rs -- do not edit.\n\
         // Source: crates/materials_data/data/nk/*.csv\n"
    )
    .unwrap();

    // Map from CSV file stem to the const name prefix used in materials_core.
    let nk_sources: &[(&str, &str)] = &[
        ("au_jc1972", "JC_AU"),
        ("ag_jc1972", "JC_AG"),
        ("cu_jc1972", "JC_CU"),
        ("au_ordal_jc", "SPLICED_AU"),
        ("cu_ordal_jc", "SPLICED_CU"),
        ("au_ordal_jc_henke", "SPLICED3_AU"),
        ("ag_ordal_jc_henke", "SPLICED3_AG"),
        ("cu_ordal_jc_henke", "SPLICED3_CU"),
    ];

    for (stem, prefix) in nk_sources {
        let csv_path = data_nk.join(format!("{stem}.csv"));
        println!("cargo:rerun-if-changed=data/nk/{stem}.csv");

        let rows = read_nk_csv(&csv_path);
        let n = rows.len();

        emit_f64_const(
            &mut nk_file,
            &format!("{prefix}_EV"),
            n,
            rows.iter().map(|r| r.0),
        );
        emit_f64_const(
            &mut nk_file,
            &format!("{prefix}_N"),
            n,
            rows.iter().map(|r| r.1),
        );
        emit_f64_const(
            &mut nk_file,
            &format!("{prefix}_K"),
            n,
            rows.iter().map(|r| r.2),
        );
    }

    // ---------- Phase 3: Drude metal parameters ----------
    let data_optical = manifest.join("data").join("optical");
    let optical_out = out_dir.join("generated_optical_params.rs");
    let drude_toml_path = data_optical.join("drude_metals.toml");
    println!("cargo:rerun-if-changed=data/optical/drude_metals.toml");

    let mut optical_file =
        File::create(&optical_out).expect("failed to create generated_optical_params.rs");
    writeln!(
        optical_file,
        "// Auto-generated by materials_data/build.rs -- do not edit.\n\
         // Source: crates/materials_data/data/optical/drude_metals.toml\n"
    )
    .unwrap();

    emit_drude_metals(&mut optical_file, &drude_toml_path);

    // ---------- Phase 4: crystal tables (placeholder) ----------
    let crystal_out = out_dir.join("generated_crystal_tables.rs");
    if !crystal_out.exists() {
        fs::write(
            &crystal_out,
            "// generated_crystal_tables.rs -- placeholder (Phase 4 / task #58 pending)\n",
        )
        .expect("failed to write generated_crystal_tables.rs");
    }
}

/// Read a CSV with header `energy_ev,n,k` and return (ev, n, k) tuples.
fn read_nk_csv(path: &PathBuf) -> Vec<(f64, f64, f64)> {
    let f = File::open(path).unwrap_or_else(|e| panic!("cannot open {path:?}: {e}"));
    let reader = BufReader::new(f);
    let mut rows = Vec::new();
    for (i, line) in reader.lines().enumerate() {
        let line = line.expect("io error reading csv");
        if i == 0 {
            continue; // skip header
        }
        let parts: Vec<&str> = line.splitn(3, ',').collect();
        assert_eq!(
            parts.len(),
            3,
            "malformed CSV row {i} in {path:?}: {line:?}"
        );
        let ev: f64 = parts[0]
            .parse()
            .unwrap_or_else(|e| panic!("bad energy_ev at row {i} in {path:?}: {e}"));
        let n: f64 = parts[1]
            .parse()
            .unwrap_or_else(|e| panic!("bad n at row {i} in {path:?}: {e}"));
        let k: f64 = parts[2]
            .parse()
            .unwrap_or_else(|e| panic!("bad k at row {i} in {path:?}: {e}"));
        rows.push((ev, n, k));
    }
    rows
}

/// Parse data/optical/drude_metals.toml and emit:
///
///   pub const NAME: [f64; 3] = [omega_p_ev, gamma_ev, eps_inf];
///
/// for each [[metals]] entry.  The caller (optical_database.rs) destructures
/// the array: `let [omega_p_ev, gamma_ev, eps_inf] = materials_data::GOLD_DRUDE;`
///
/// Intentionally hand-rolled (no toml crate build-dep) since the schema is a
/// flat array-of-tables with only string and float scalar values.  Parsing rules:
///   - Lines starting with "#" or empty lines are ignored.
///   - "[[metals]]" opens a new entry (stores any in-progress entry first).
///   - "key = value" pairs set fields in the current entry.
///   - String values may be quoted; float values are bare decimals.
fn emit_drude_metals(out: &mut File, path: &PathBuf) {
    let raw = fs::read_to_string(path).unwrap_or_else(|e| panic!("cannot read {path:?}: {e}"));

    // Collect entries as (name, omega_p, gamma, eps_inf).
    let mut entries: Vec<(String, f64, f64, f64)> = Vec::new();
    let mut cur_name: Option<String> = None;
    let mut cur_omega_p: Option<f64> = None;
    let mut cur_gamma: Option<f64> = None;
    let mut cur_eps: Option<f64> = None;

    let flush = |entries: &mut Vec<_>,
                 name: &mut Option<String>,
                 omega_p: &mut Option<f64>,
                 gamma: &mut Option<f64>,
                 eps: &mut Option<f64>| {
        if let Some(n) = name.take() {
            entries.push((
                n.clone(),
                omega_p
                    .take()
                    .unwrap_or_else(|| panic!("missing omega_p_ev for {n}")),
                gamma
                    .take()
                    .unwrap_or_else(|| panic!("missing gamma_ev for {n}")),
                eps.take()
                    .unwrap_or_else(|| panic!("missing eps_inf for {n}")),
            ));
        }
    };

    for line in raw.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        if line == "[[metals]]" {
            flush(
                &mut entries,
                &mut cur_name,
                &mut cur_omega_p,
                &mut cur_gamma,
                &mut cur_eps,
            );
            continue;
        }
        if let Some((k, v)) = line.split_once('=') {
            let k = k.trim();
            let v = v.trim().trim_matches('"');
            match k {
                "name" => cur_name = Some(v.to_owned()),
                "omega_p_ev" => {
                    cur_omega_p = Some(v.parse().unwrap_or_else(|e| panic!("bad omega_p_ev: {e}")))
                }
                "gamma_ev" => {
                    cur_gamma = Some(v.parse().unwrap_or_else(|e| panic!("bad gamma_ev: {e}")))
                }
                "eps_inf" => {
                    cur_eps = Some(v.parse().unwrap_or_else(|e| panic!("bad eps_inf: {e}")))
                }
                _ => {} // reference and other fields ignored
            }
        }
    }
    flush(
        &mut entries,
        &mut cur_name,
        &mut cur_omega_p,
        &mut cur_gamma,
        &mut cur_eps,
    );

    for (name, omega_p, gamma, eps_inf) in &entries {
        writeln!(out, "/// `[omega_p_ev, gamma_ev, eps_inf]` for {name}.").unwrap();
        writeln!(out, "#[allow(dead_code)]").unwrap();
        writeln!(
            out,
            "pub const {name}: [f64; 3] = [{omega_p:?}, {gamma:?}, {eps_inf:?}];\n"
        )
        .unwrap();
    }
}

/// Write `pub const NAME: [f64; N] = [...];` to the output file.
/// Prefixed with `#[allow(dead_code)]` so warnings-as-errors does not fire
/// during the migration phase before materials_core is wired in.
fn emit_f64_const(out: &mut File, name: &str, n: usize, values: impl Iterator<Item = f64>) {
    writeln!(out, "#[allow(dead_code)]").unwrap();
    write!(out, "pub const {name}: [f64; {n}] = [\n    ").unwrap();
    let vals: Vec<f64> = values.collect();
    for (i, v) in vals.iter().enumerate() {
        if i > 0 && i % 9 == 0 {
            write!(out, "\n    ").unwrap();
        }
        write!(out, "{v:?}, ").unwrap();
    }
    writeln!(out, "\n];").unwrap();
}
