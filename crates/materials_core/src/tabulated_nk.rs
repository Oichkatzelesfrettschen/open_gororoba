/// Linear interpolation on a sorted ascending grid.
///
/// Clamps to ys[0] below xs[0] and ys[n-1] above xs[n-1].
fn interp_linear(xs: &[f64], ys: &[f64], x: f64) -> f64 {
    let n = xs.len();
    if n == 0 {
        return 0.0;
    }
    if x <= xs[0] {
        return ys[0];
    }
    if x >= xs[n - 1] {
        return ys[n - 1];
    }
    let i = xs
        .partition_point(|&xi| xi <= x)
        .saturating_sub(1)
        .min(n - 2);
    let t = (x - xs[i]) / (xs[i + 1] - xs[i]);
    ys[i] * (1.0 - t) + ys[i + 1] * t
}

