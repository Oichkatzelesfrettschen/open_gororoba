//! # Physics-First Falsification Sources
//!
//! This note records the bounded external sources used to justify the new
//! physics-first falsification lane. The goal is not to treat higher algebra as
//! physics evidence by itself; it is to tie descriptor design and evaluation to
//! official event labels, predictive baselines, and mathematically explicit zero-
//! divisor geometry.
//!
//! ## Official label surfaces
//!
//! - NASA DONKI API root: <https://api.nasa.gov/>
//! - NASA API authentication note: <https://api.nasa.gov/assets/html/authentication.html>
//! - CCMC DONKI system page: <https://ccmc.gsfc.nasa.gov/tools/DONKI/>
//! - CCMC DONKI webservice announcement: <https://ccmc.gsfc.nasa.gov/news/announcing-donki/>
//!
//! These surfaces motivate the current bounded official label families:
//!
//! - `IPS` for interplanetary shocks
//! - `GST` for geomagnetic storm onset
//! - `SEP` for solar energetic particle onset
//! - `FLR` for solar flare timing as an origin-side official label
//!
//! ## Predictive baseline context
//!
//! The current supervised heliosphere lane is intentionally modest: invariant-only
//! thresholds and regularized logistic models compete against the existing scalar
//! event score. That design is informed by operational CME-arrival and disturbance
//! forecast practice, where official label surfaces and forecast residuals matter
//! more than exotic latent geometry by itself.
//!
//! Context references used for this tranche:
//!
//! - CCMC CME Scoreboard family and operational comparison context via CCMC:
//!   <https://ccmc.gsfc.nasa.gov/>
//! - Example recent operational forecast evaluation paper:
//!   "The ap Prediction Tool Implemented by the A.Ne.Mo.S./NKUA Group"
//!   <https://www.mdpi.com/2073-4433/15/9/1073>
//!
//! ## Higher-algebra geometry context
//!
//! These references motivate the descriptor family as adaptive geometry and sparse
//! occupancy structure, not as evidence that the plasma "is" sedenionic.
//!
//! - Robert de Marrais, "The 42 Assessors and the Box-Kites they fly"
//!   <https://arxiv.org/abs/math/0011260>
//! - Robert de Marrais, "Placeholder Substructures III"
//!   <https://arxiv.org/abs/0704.0112>
//! - "The geometry of sedenion zero divisors"
//!   <https://arxiv.org/abs/2411.18881>
//!
//! ## Working rule
//!
//! The repo should only treat higher-order algebra as physically meaningful when
//! it improves one of the following on held-out or cross-mission data:
//!
//! - event prediction
//! - cross-platform invariance
//! - information-preserving sparsification under fixed GPU budgets
//!
//! Anything less is recorded as structural or descriptive, not as a discovery.
//!
