//! # Unified Repo Constitution
//!
//! ## Mission
//! Build `lambda_gororoba` as a unified, reproducible, multi-module lambda research system that preserves source provenance while creating new first-party scientific and engineering value.
//!
//! ## Principles
//! 1. Non-destructive integration.
//! 2. Root workspace as source of truth.
//! 3. Manual singular-repo operation from root module trees.
//! 4. Evidence-first decisions with timestamped artifacts.
//! 5. Module boundaries preserved unless explicitly re-specified.
//! 6. Legal and installation metadata remain module-canonical.
//! 7. Warning findings are treated as blocking risks.
//!
//! ## Constitutional Layers
//! - Layer 1: singular module trees (`research/`, `experiments/`, `learner/`).
//! - Layer 2: archived provenance snapshots (`archive/intake_lane_retirement/<TS>/merge_in/*`).
//! - Layer 3: first-party synthesis (`docs/first_party/*`, root governance, and orchestrator scripts).
//!
//! ## Governance Invariants
//! - Every deterministic process writes a timestamped artifact under `logs/`.
//! - Every archive move must be hash-verified and reversible.
//! - Every policy must have an automated verifier when feasible.
//! - Every unresolved conflict must be recorded with owner, action, and evidence.
//!
//! ## Scientific Position
//! The repository is treated as a composite research instrument:
//! - documentation corpus,
//! - experiment corpus,
//! - verification corpus,
//! - integration corpus.
//!
//! Synthesis is additive: knowledge is transformed and reconciled, not discarded.
//!
