fn run_audit(streams: &[DataStream]) -> (bool, String) {
    let all_null = streams
        .iter()
        .all(|s| s.verdict == "null" && s.exclusion_cl >= NULL_RESULT_CL_THRESHOLD);

    let mut toml = String::new();
    writeln!(toml, "# Sterile Neutrino Null Result Audit -- E-039").unwrap();
    writeln!(
        toml,
        "# Generated by sterile-neutrino-audit (crates/gororoba_cli)"
    )
    .unwrap();
    writeln!(toml).unwrap();
    writeln!(toml, "[audit]").unwrap();
    writeln!(toml, r#"experiment = "E-039""#).unwrap();
    writeln!(toml, r#"date = "2026-02-18""#).unwrap();
    writeln!(
        toml,
        r#"verdict = "{}""#,
        if all_null { "null_confirmed" } else { "inconclusive" }
    )
    .unwrap();
    writeln!(toml, "stream_count = {}", streams.len()).unwrap();
    writeln!(
        toml,
        "null_streams = {}",
        streams.iter().filter(|s| s.verdict == "null").count()
    )
    .unwrap();
    writeln!(toml).unwrap();
    writeln!(toml, "[[stream]]").unwrap();
    for (i, s) in streams.iter().enumerate() {
        if i > 0 {
            writeln!(toml).unwrap();
            writeln!(toml, "[[stream]]").unwrap();
        }
        writeln!(toml, r#"claim_id = "{}""#, s.claim_id).unwrap();
        writeln!(toml, r#"experiment = "{}""#, s.experiment).unwrap();
        writeln!(toml, r#"channel = "{}""#, s.channel).unwrap();
        writeln!(toml, r#"reference = "{}""#, s.reference).unwrap();
        writeln!(toml, "exclusion_cl = {:.4}", s.exclusion_cl).unwrap();
        writeln!(toml, r#"verdict = "{}""#, s.verdict).unwrap();
    }

    (all_null, toml)
}

fn main() {
    let args = Args::parse();
    let streams = audit_streams();
    let (all_null, report) = run_audit(&streams);

    if let Some(path) = &args.output {
        std::fs::write(path, &report).unwrap_or_else(|e| {
            eprintln!("ERROR: could not write {path}: {e}");
            std::process::exit(1);
        });
        println!("Wrote audit report to {path}");
    } else {
        print!("{report}");
    }

    if all_null {
        println!(
            "AUDIT COMPLETE: {} / {} streams return null at >= {:.0}% CL -- light sterile neutrino excluded.",
            streams.iter().filter(|s| s.verdict == "null").count(),
            streams.len(),
            NULL_RESULT_CL_THRESHOLD * 100.0,
        );
    } else {
        println!("AUDIT INCONCLUSIVE: not all streams return null above threshold.");
        std::process::exit(1);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_audit_all_null() {
        let streams = audit_streams();
        let (all_null, _) = run_audit(&streams);
        assert!(all_null, "all audit streams should return null");
    }

    #[test]
    fn test_stream_count() {
        let streams = audit_streams();
        assert_eq!(streams.len(), 6, "six primary data streams in the 2025-2026 audit");
    }

    #[test]
    fn test_minimum_cl_threshold() {
        let streams = audit_streams();
        for s in &streams {
            assert!(
                s.exclusion_cl >= NULL_RESULT_CL_THRESHOLD,
                "stream {} has exclusion CL {:.3} below threshold {:.3}",
                s.claim_id,
                s.exclusion_cl,
                NULL_RESULT_CL_THRESHOLD,
            );
        }
    }

    #[test]
    fn test_report_toml_contains_claims() {
        let streams = audit_streams();
        let (_, report) = run_audit(&streams);
        for s in &streams {
            assert!(
                report.contains(s.claim_id),
                "report should reference claim {}",
                s.claim_id
            );
        }
    }
}
