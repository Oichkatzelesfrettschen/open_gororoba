//! # Algebraic Wick Rotation and the Emergence of Time
//!
//! This section details the theoretical framework for the emergence of time
//! through the complexification and rotation of non-associative algebras.
//!
//! ## 1. The Euclidean Octonion Vacuum
//!
//! The standard octonions $\mathbb{O}$ possess a purely Euclidean signature
//! $(+,+,+,+,+,+,+,+)$. In this state, the universe is a static, 8-dimensional
//! Riemannian manifold without a temporal dimension.
//!
//! ## 2. Algebraic Wick Rotation (The Twist)
//!
//! Instead of a coordinate transformation $t \to it$, the project proposes
//! an **Algebraic Wick Rotation**.
//!
//! This is achieved via a **Drinfeld twist** or a morphism that transforms
//! the octonions into **Split-Octonions** $\mathbb{O}_s$.
//!
//! ## 3. Emergent Lorentzian Signature
//!
//! The split-octonions possess a Lorentzian/hyperbolic signature $(+,+,+,+,-,-,-,-)$.
//!
//! The introduction of the "minus" signs into the algebraic norm provides the
//! necessary causal structure.
//!
//! - **The Split:** One set of coordinates becomes "spacelike," while the
//!   antisymmetric counterparts become "timelike."
//! - **Update Steps:** In this framework, time is not a fundamental dimension
//!   but the cumulative "arc length" of non-associative update steps required
//!   to synchronize the vacuum state space.
//!
//! ## 4. Physical Implication: The Dirac Equation
//!
//! The split-octonionic Dirac equation (Koeplinger & Gogberashvili) naturally
//! incorporates the Lorentz boost generators as algebraic automorphisms.
//!
//! In the project's **Thesis 2**, the "flow of time" is physically modeled as
//! the process of the non-associative degrees of freedom "associating" or
//! decohering into the observable, 4D associative spacetime.
