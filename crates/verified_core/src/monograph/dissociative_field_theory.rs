//! # Dissociative Field Theory (DFT)
//!
//! This section formalizes the hierarchical mapping of physical forces to
//! successive Cayley-Dickson layers, known as Dissociative Field Theory (DFT).
//!
//! ## 1. The Force Hierarchy
//!
//! DFT posits that each physical force emerges as a resonant mode at a specific
//! algebraic dimension doubling. As the algebra doubles, new "degrees of
//! dissociation" (non-commutativity, non-associativity) are introduced,
//! manifesting as new physical interactions.
//!
//! | Dimension | Algebra | Physical Sector | Property Emergence |
//! | :--- | :--- | :--- | :--- |
//! | **1D** | Reals | Scalar Gravity / Mass | Ordering |
//! | **2D** | Complex | Temporal Flux / Phase | Phase Rotation |
//! | **4D** | Quaternions | Spacetime Metric (GR) | Non-commutativity |
//! | **8D** | Octonions | Magnetism / Strong Force | Non-associativity |
//! | **16D** | Sedenions | Electricity / Weak Isospin | Zero Divisors |
//! | **32D** | Pathions | Weak Nuclear Force | Non-alternativity |
//! | **64D** | Chingons | Strong Nuclear Force | High-order Harmonics |
//! | **256D** | Voudons | Dark Energy / Homogeneity | Global Frustration |
//!
//! ## 2. The Dissociation Mechanism
//!
//! The term "Dissociative" refers to the process where the unified force field
//! breaks its internal symmetries through the loss of algebraic identities.
//!
//! - **The Octonionic Split:** At 8D, the loss of associativity "dissociates" the
//!   strong force from the gravitational background.
//! - **The Sedenionic Split:** At 16D, the emergence of zero divisors dissociates
//!   the electromagnetic field, allowing for charge-sign independence.
//!
//! ## 3. Synthesis: Unified Algebraic Action
//!
//! The DFT Lagrangian is a sum over the curvature terms of each sector:
//!
//! $$\mathcal{L}_{DFT} = \sum_{n=0}^{N} \alpha_n \mathcal{R}(2^n)$$
//!
//! where $\mathcal{R}(2^n)$ is the Ricci-like curvature tensor constructed from
//! the $2^n$-dimensional Cayley-Dickson manifold.
//!
