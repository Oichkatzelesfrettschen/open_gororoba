//! ## 1. The Cayley Integers (Octavians)
//!
//! The set of octonions with integer coordinates is not closed under multiplication.
//! To form a ring of integers, one must include specific half-integer points.
//!
//! The **Cayley Integers** (or Octavian integers) consist of:
//! - 16 roots of the form $\pm e_i$.
//! - 112 roots of the form $\frac{1}{2}(\pm 1 \pm e_i \pm e_j \pm e_k)$ where $\{i, j, k\}$ is a Fano line.
//! - 112 roots of the form $\frac{1}{2}(\pm e_p \pm e_q \pm e_r \pm e_s)$ where $\{p, q, r, s\}$ is a Fano complement.
//!
//! **Total: $16 + 112 + 112 = 240$ units.**
//!
//! ## 2. The E8 Lattice Roots
//!
//! These 240 units are precisely the 240 roots of the $E_8$ lattice, the unique
//! even, unimodular lattice of rank 8.
//!
//! This provides the algebraic anchor for **E8 Unification**: the fundamental
//! generators of the unified force (gauge bosons) are the shortest vectors
//! in the integral octonionic vacuum.
//!
//! ## 3. Symmetry: The Kleinian Group $PSL(2,7)$
