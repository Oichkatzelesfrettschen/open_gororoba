(** A first geometry-shaped arbitrary-a package.

    Instead of assuming `is_h_module_dim` directly, this package records the
    concrete dimensional shadow of Moreno's geometric claim: V_lambda(a)
    decomposes into a finite number of quaternionic 4-blocks.  From that block
    count we derive both the H-module-dimension predicate and the mod-4
    conclusion.  This is still weaker than a full formalization of the
    subspace geometry, but it is closer to Moreno's actual proof shape than
    the earlier witness-only package. *)
Record Moreno16ArbitraryAGeometricVlambdaData := {
  moreno16_geom_a : CDOct;
  moreno16_geom_a_unit : oct_norm_sq moreno16_geom_a = 1%R;
  moreno16_geom_a_pure :
    oct_conj moreno16_geom_a = oct_neg moreno16_geom_a;
  moreno16_geom_lambda : R;
  moreno16_geom_lambda_pos : (0 < moreno16_geom_lambda)%R;
  moreno16_geom_vlambda_dim : nat;
  moreno16_geom_block_count : nat;
  moreno16_geom_vlambda_dim_is_blocks :
    moreno16_geom_vlambda_dim = 4 * moreno16_geom_block_count
}.

Theorem moreno16_geometry_is_h_module_dim :
  forall G : Moreno16ArbitraryAGeometricVlambdaData,
    is_h_module_dim (moreno16_geom_vlambda_dim G).
Proof.
  intro G.
  rewrite (moreno16_geom_vlambda_dim_is_blocks G).
  exact (div4_implies_h_module_dim (moreno16_geom_block_count G)).
Qed.

Theorem moreno16_concrete_witness_dim_div4 :
  forall W : Moreno16ConcreteVlambdaWitness,
    exists k : nat, moreno16_concrete_vlambda_dim W = 4 * k.
Proof.
  intro W.
  exact (FinDimHModule.h_module_dim_div4
           (moreno16_concrete_vlambda_dim W)
           (moreno16_concrete_vlambda_is_h_module_dim W)).
Qed.

Corollary moreno16_concrete_witness_dim_mod4 :
  forall W : Moreno16ConcreteVlambdaWitness,
    Nat.modulo (moreno16_concrete_vlambda_dim W) 4 = 0.
Proof.
  intro W.
  destruct (moreno16_concrete_witness_dim_div4 W) as [k Hk].
  rewrite Hk.
  rewrite Nat.mul_comm.
  apply Nat.Div0.mod_mul.
Qed.

Theorem moreno16_arbitrary_a_dim_div4 :
  forall H : Moreno16ArbitraryAConcreteHypotheses,
    exists k : nat,
      moreno16_concrete_vlambda_dim (moreno16_concrete_witness H) = 4 * k.
Proof.
  intro H.
  exact (moreno16_concrete_witness_dim_div4 (moreno16_concrete_witness H)).
Qed.

Corollary moreno16_arbitrary_a_dim_mod4 :
  forall H : Moreno16ArbitraryAConcreteHypotheses,
    Nat.modulo (moreno16_concrete_vlambda_dim (moreno16_concrete_witness H)) 4 = 0.
Proof.
  intro H.
  exact (moreno16_concrete_witness_dim_mod4 (moreno16_concrete_witness H)).
Qed.

Definition moreno16_canonical_vlambda_witness : Moreno16ConcreteVlambdaWitness.
Proof.
  refine {| moreno16_concrete_lambda := 1%R;
            moreno16_concrete_lambda_pos := Rlt_0_1;
            moreno16_concrete_vlambda_dim := 4%nat;
            moreno16_concrete_vlambda_is_h_module_dim := moreno16_hmd_4 |}.
Defined.

Lemma moreno16_canonical_a_unit :
  oct_norm_sq moreno_a = 1%R.
Proof.
  unfold moreno_a.
  apply oct_basis_unit_norm.
  lia.
Qed.

Lemma moreno16_canonical_a_pure :
  oct_conj moreno_a = oct_neg moreno_a.
Proof.
  unfold moreno_a.
  cbv [oct_conj oct_neg oct_e oct_lo oct_hi
       quat_conj quat_neg quat_zero quat_one qa qb qc qd].
  apply (f_equal2 mkOct); apply (f_equal4 mkQuat); ring.
Qed.

Definition moreno16_canonical_arbitrary_a_hypotheses :
  Moreno16ArbitraryAConcreteHypotheses.
Proof.
  refine {| moreno16_concrete_a := moreno_a;
            moreno16_concrete_a_unit := moreno16_canonical_a_unit;
            moreno16_concrete_a_pure := moreno16_canonical_a_pure;
            moreno16_concrete_witness := moreno16_canonical_vlambda_witness |}.
Defined.

Definition moreno16_build_arbitrary_a_concrete_hypotheses
  (a : CDOct)
  (Ha_unit : oct_norm_sq a = 1%R)
  (Ha_pure : oct_conj a = oct_neg a)
  (W : Moreno16ConcreteVlambdaWitness)
  : Moreno16ArbitraryAConcreteHypotheses :=
  {| moreno16_concrete_a := a;
     moreno16_concrete_a_unit := Ha_unit;
     moreno16_concrete_a_pure := Ha_pure;
     moreno16_concrete_witness := W |}.

Definition moreno16_arbitrary_witness_to_concrete
  (W : Moreno16ArbitraryAVlambdaWitness)
  : Moreno16ConcreteVlambdaWitness :=
  {| moreno16_concrete_lambda := moreno16_arbitrary_lambda W;
     moreno16_concrete_lambda_pos := moreno16_arbitrary_lambda_pos W;
     moreno16_concrete_vlambda_dim := moreno16_arbitrary_vlambda_dim W;
     moreno16_concrete_vlambda_is_h_module_dim :=
       moreno16_arbitrary_vlambda_is_h_module_dim W |}.

Definition moreno16_arbitrary_witness_to_hypotheses
  (W : Moreno16ArbitraryAVlambdaWitness)
  : Moreno16ArbitraryAConcreteHypotheses :=
  moreno16_build_arbitrary_a_concrete_hypotheses
    (moreno16_arbitrary_a W)
    (moreno16_arbitrary_a_unit W)
    (moreno16_arbitrary_a_pure W)
    (moreno16_arbitrary_witness_to_concrete W).

Definition moreno16_build_arbitrary_a_witness_from_concrete_hypotheses
  (H : Moreno16ArbitraryAConcreteVlambdaHypotheses)
  : Moreno16ArbitraryAVlambdaWitness :=
  {| moreno16_arbitrary_a := moreno16_concrete_hyp_a H;
     moreno16_arbitrary_a_unit := moreno16_concrete_hyp_a_unit H;
     moreno16_arbitrary_a_pure := moreno16_concrete_hyp_a_pure H;
     moreno16_arbitrary_lambda := moreno16_concrete_hyp_lambda H;
     moreno16_arbitrary_lambda_pos := moreno16_concrete_hyp_lambda_pos H;
     moreno16_arbitrary_vlambda_dim := moreno16_concrete_hyp_vlambda_dim H;
     moreno16_arbitrary_vlambda_is_h_module_dim :=
       moreno16_concrete_hyp_vlambda_is_h_module_dim H |}.

Definition moreno16_geometry_to_concrete_hypotheses
  (G : Moreno16ArbitraryAGeometricVlambdaData)
  : Moreno16ArbitraryAConcreteVlambdaHypotheses :=
  {| moreno16_concrete_hyp_a := moreno16_geom_a G;
     moreno16_concrete_hyp_a_unit := moreno16_geom_a_unit G;
     moreno16_concrete_hyp_a_pure := moreno16_geom_a_pure G;
     moreno16_concrete_hyp_lambda := moreno16_geom_lambda G;
