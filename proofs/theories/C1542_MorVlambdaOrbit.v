(** * C1542_MorVlambdaOrbit: Moreno (1997) Theorem 1.16 -- abstract orbit/module lane.

    Moreno's proof of Theorem 1.16 is structural: for lambda > 0, each
    eigenspace V_lambda carries a quaternionic orbit structure generated by
    the H_a action, so dim_R V_lambda is divisible by 4.

    In this repo the finite-dimensional H-module dimension theorem already
    lives in HModuleDim.v / FinDimHModule.v.  This file packages that result
    as the paper-scoped abstract Moreno lane:

    - if V_lambda is presented as a finite-dimensional right H-module, then
      dim_R V_lambda = 4k
    - equivalently, dim_R V_lambda = 0 mod 4

    The remaining open bridge is to instantiate these module hypotheses from
    the concrete Cayley-Dickson subspace V_lambda inside H_a^perp for an
    arbitrary doubly-pure unit-norm a.  The canonical A_3 witness lives in
    C1542_MorVlambdaMod4.v. *)

From Stdlib Require Import Reals Arith PeanoNat Lia.
From OpenGororoba Require Import Prelude FinDimHModule HModuleDim.

Open Scope R_scope.
Open Scope nat_scope.

Module Type MorenoVlambdaModule.
  Include HModuleFinDim.
  Parameter lambda : R.
  Axiom lambda_pos : (0 < lambda)%R.
End MorenoVlambdaModule.

Module MorenoVlambdaDim (M : MorenoVlambdaModule).
  Module Import Dim := HModDimThm M.

  Theorem moreno16_vlambda_dim_div4 :
    exists k : nat, M.v_dim = 4 * k.
  Proof.
    exact h_module_dim_div4.
  Qed.

  Corollary moreno16_vlambda_dim_mod4 :
    Nat.modulo M.v_dim 4 = 0.
  Proof.
    destruct moreno16_vlambda_dim_div4 as [k Hk].
    rewrite Hk.
    rewrite Nat.mul_comm.
    apply Nat.Div0.mod_mul.
  Qed.
End MorenoVlambdaDim.

Section Moreno16OrbitPredicate.
  Variable vl_dim : nat.
  Hypothesis Hvl_dim : is_h_module_dim vl_dim.

  Theorem moreno16_orbit_dim_div4 :
    exists k : nat, vl_dim = 4 * k.
  Proof.
    exact (FinDimHModule.h_module_dim_div4 vl_dim Hvl_dim).
  Qed.

  Corollary moreno16_orbit_dim_mod4 :
    Nat.modulo vl_dim 4 = 0.
  Proof.
    destruct moreno16_orbit_dim_div4 as [k Hk].
    rewrite Hk.
    rewrite Nat.mul_comm.
    apply Nat.Div0.mod_mul.
  Qed.
End Moreno16OrbitPredicate.

Example moreno16_hmd_4 :
  is_h_module_dim 4.
Proof.
  apply hmd_step; [lia | exact hmd_zero].
Qed.

Example moreno16_hmd_8 :
  is_h_module_dim 8.
Proof.
  apply hmd_step; [lia | exact moreno16_hmd_4].
Qed.

Example moreno16_example_dim4 :
  exists k : nat, 4 = 4 * k.
Proof.
  exact (moreno16_orbit_dim_div4 4 moreno16_hmd_4).
Qed.

Example moreno16_example_dim8 :
  Nat.modulo 8 4 = 0.
Proof.
  exact (moreno16_orbit_dim_mod4 8 moreno16_hmd_8).
Qed.
