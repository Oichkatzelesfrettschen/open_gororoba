(** * C1542_MorVlambdaOrbit: Moreno (1997) Theorem 1.16 -- abstract orbit/module lane.

    Moreno's proof of Theorem 1.16 is structural: for lambda > 0, each
    eigenspace V_lambda carries a quaternionic orbit structure generated by
    the H_a action, so dim_R V_lambda is divisible by 4.

    In this repo the finite-dimensional H-module dimension theorem already
    lives in HModuleDim.v / FinDimHModule.v.  This file packages that result
    as the paper-scoped abstract Moreno lane:

    - if V_lambda is presented as a finite-dimensional right H-module, then
      dim_R V_lambda = 4k
    - equivalently, dim_R V_lambda = 0 mod 4

    The remaining open bridge is to instantiate these module hypotheses from
    the concrete Cayley-Dickson subspace V_lambda inside H_a^perp for an
    arbitrary doubly-pure unit-norm a.  The canonical A_3 witness lives in
    C1542_MorVlambdaMod4.v. *)

From Stdlib Require Import Reals Arith PeanoNat Lia.
