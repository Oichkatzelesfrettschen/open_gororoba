Definition moreno16_concrete_hypotheses_to_hypotheses
  (H : Moreno16ArbitraryAConcreteVlambdaHypotheses)
  : Moreno16ArbitraryAConcreteHypotheses :=
  moreno16_arbitrary_witness_to_hypotheses
