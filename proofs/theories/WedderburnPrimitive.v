Theorem wedderburn_generalized_nonzero_two_sided_inverse :
  forall c2 c3 : R, forall q : CDQuat,
    wedderburn_base_norm_anisotropic c2 ->
    ~ wedderburn_base_norm_represents c2 c3 ->
