(** Wedderburn's key structural fact used in our proofs:

    Every finitely generated module over a division ring (= primitive
    algebra in Wedderburn's terminology) is free, and therefore has
    dimension divisible by the dimension of the division ring.

    For H (quaternions, dim 4): every H-module has dim = 4k.

    This is the conceptual foundation for:
    - FinDimHModule.is_h_module_dim
    - HModuleDim.h_module_dim_div4
    - C1543_MorMod4Bound.cor_1_17_mod4 *)

(** The quaternion case of Wedderburn's theorem:
    H is a primitive algebra with n = 2, theta = conjugate, g = -1.
    The relation xy = y*conj(x), y^2 = -1 generates H from {x, y}
    where x = i and y = j give k = ij.

    This is exactly the quaternion multiplication table from
    Dickson (1919) eq.3, formalized in DicksonCDProcess.v. *)

(** Wedderburn surface used downstream: valid quaternion-module dimensions
    are multiples of 4. This is the nat-level form of the standard
    division-ring module theorem specialized to H. *)
Theorem wedderburn_h_module_dim_div4 : forall d : nat,
  is_h_module_dim d -> exists k : nat, d = (4 * k)%nat.
Proof.
  exact FinDimHModule.h_module_dim_div4.
Qed.

(** Exact characterization of the valid H-module dimensions. *)
Theorem wedderburn_h_module_dim_iff_div4 : forall d : nat,
  is_h_module_dim d <-> exists k : nat, d = (4 * k)%nat.
Proof.
  exact FinDimHModule.h_module_dim_iff_div4.
Qed.

(** Mod-4 corollary used by the Moreno lane. *)
Theorem wedderburn_h_module_dim_mod4 : forall d : nat,
  is_h_module_dim d -> Nat.modulo d 4%nat = 0%nat.
Proof.
  exact FinDimHModule.h_module_dim_mod4.
Qed.

Record WedderburnCyclicN2Surface (A : Type) := {
  wcy_mul : A -> A -> A;
  wcy_theta : A -> A;
  wcy_x : A;
  wcy_y : A;
  wcy_g : A;
  wcy_cyclic_relation :
    wcy_mul wcy_x wcy_y = wcy_mul wcy_y (wcy_theta wcy_x);
  wcy_y_square : wcy_mul wcy_y wcy_y = wcy_g;
}.

Record WedderburnPrimitiveN2Surface (A : Type) := {
  wp_cyclic_surface : WedderburnCyclicN2Surface A;
  wp_one : A;
  wp_det : A -> R;
  wp_norm : A -> R;
  wp_inv : A -> A;
  wp_det_norm_sq : forall z : A, wp_det z = (wp_norm z)^2;
  wp_det_nonzero_iff_norm_nonzero :
    forall z : A, wp_det z <> 0 <-> wp_norm z <> 0;
  wp_right_inverse :
    forall z : A, wp_det z <> 0 ->
      @wcy_mul A wp_cyclic_surface z (wp_inv z) = wp_one;
  wp_left_inverse :
    forall z : A, wp_det z <> 0 ->
      @wcy_mul A wp_cyclic_surface (wp_inv z) z = wp_one;
}.

Fixpoint wedderburn_right_pow {A : Type}
    (mul : A -> A -> A) (one y : A) (n : nat) : A :=
  match n with
  | O => one
  | S k => mul (wedderburn_right_pow mul one y k) y
  end.

Fixpoint wedderburn_section1_sum {A : Type}
    (add : A -> A -> A) (zero : A) (f : nat -> A) (n : nat) : A :=
  match n with
  | O => zero
  | S k => add (wedderburn_section1_sum add zero f k) (f k)
  end.

Record WedderburnSection1CyclicPresentationSurface (A : Type) := {
  wcp_mul : A -> A -> A;
  wcp_add : A -> A -> A;
  wcp_zero : A;
  wcp_one : A;
  wcp_x : A;
  wcp_y : A;
  wcp_theta : A -> A;
  wcp_g : A;
  wcp_n : nat;
  wcp_coeff : nat -> A -> A;
  wcp_cyclic_relation :
    wcp_mul wcp_x wcp_y = wcp_mul wcp_y (wcp_theta wcp_x);
  wcp_y_power :
    wedderburn_right_pow wcp_mul wcp_one wcp_y wcp_n = wcp_g;
  wcp_decomposition :
    forall z : A,
      z =
      wedderburn_section1_sum wcp_add wcp_zero
        (fun k => wcp_mul (wedderburn_right_pow wcp_mul wcp_one wcp_y k)
                          (wcp_coeff k z))
        wcp_n;
}.

Record WedderburnSection1AssociativePresentationSurface (A : Type) := {
  wcpa_presentation_surface : WedderburnSection1CyclicPresentationSurface A;
  wcpa_mul_assoc :
    forall a b c : A,
      @wcp_mul A wcpa_presentation_surface
        (@wcp_mul A wcpa_presentation_surface a b) c =
      @wcp_mul A wcpa_presentation_surface a
        (@wcp_mul A wcpa_presentation_surface b c);
  wcpa_mul_one_left :
    forall a : A,
      @wcp_mul A wcpa_presentation_surface (@wcp_one A wcpa_presentation_surface) a = a;
  wcpa_mul_one_right :
    forall a : A,
      @wcp_mul A wcpa_presentation_surface a (@wcp_one A wcpa_presentation_surface) = a;
}.

Definition wedderburn_section1_assoc_presentation_to_cyclic_n2 {A : Type}
    (S : WedderburnSection1AssociativePresentationSurface A)
    (Hn : @wcp_n A (wcpa_presentation_surface A S) = 2%nat)
    : WedderburnCyclicN2Surface A.
Proof.
  refine
    {| wcy_mul := @wcp_mul A (wcpa_presentation_surface A S);
       wcy_theta := @wcp_theta A (wcpa_presentation_surface A S);
       wcy_x := @wcp_x A (wcpa_presentation_surface A S);
       wcy_y := @wcp_y A (wcpa_presentation_surface A S);
       wcy_g := @wcp_g A (wcpa_presentation_surface A S) |}.
  - exact (@wcp_cyclic_relation A (wcpa_presentation_surface A S)).
  - pose proof (@wcp_y_power A (wcpa_presentation_surface A S)) as Hy.
    rewrite Hn in Hy.
    simpl in Hy.
    rewrite (@wcpa_mul_one_left A S (@wcp_y A (wcpa_presentation_surface A S))) in Hy.
    exact Hy.
Defined.

(** Wedderburn's cyclic presentation in the quaternion case:
    choose x = i and y = j. Then xy = y * theta(x) with theta = conjugation,
    and y^2 = -1. *)
Theorem wedderburn_quaternion_cyclic_relation :
  quat_mul qi qj = quat_mul qj (quat_conj qi).
Proof.
  unfold qi, qj, quat_conj, quat_mul.
  simpl.
  f_equal; ring.
Qed.

Theorem wedderburn_quaternion_y_square :
  quat_mul qj qj = quat_neg quat_one.
Proof.
  unfold qj, quat_neg, quat_one, quat_mul.
  simpl.
  f_equal; ring.
Qed.

Definition wedderburn_quaternion_cyclic_surface :
    WedderburnCyclicN2Surface CDQuat :=
  {| wcy_mul := quat_mul;
     wcy_theta := quat_conj;
     wcy_x := qi;
     wcy_y := qj;
     wcy_g := quat_neg quat_one;
     wcy_cyclic_relation := wedderburn_quaternion_cyclic_relation;
     wcy_y_square := wedderburn_quaternion_y_square |}.

(** The full quaternion basis is generated from the cyclic pair {i, j}. *)
Theorem wedderburn_quaternion_cyclic_generation :
  qk = quat_mul qi qj /\
  qi = quat_mul qj qk /\
  qj = quat_mul qk qi.
Proof.
  repeat split.
  - symmetry. exact dickson_eq3_ij.
  - symmetry. exact dickson_eq3_jk.
  - symmetry. exact dickson_eq3_ki.
Qed.

Definition wedderburn_quaternion_left_det (q : CDQuat) : R :=
  dickson1921_matrix_det4 (quat_hamilton_entry q).

(** Wedderburn's determinant criterion, specialized to the quaternion case:
    the left-multiplication determinant is exactly the norm square squared. *)
Theorem wedderburn_quaternion_det_equals_norm_sq :
  forall q : CDQuat,
    wedderburn_quaternion_left_det q = (quat_norm_sq q)^2.
Proof.
  intro q.
  unfold wedderburn_quaternion_left_det.
  unfold dickson1921_matrix_det4.
  repeat rewrite <- dickson1921_param_matrix_specializes_to_standard.
  exact (proj1 (dickson1921_param_quaternion_case q)).
Qed.

Theorem wedderburn_quaternion_det_nonzero_iff_norm_nonzero :
  forall q : CDQuat,
    wedderburn_quaternion_left_det q <> 0 <-> quat_norm_sq q <> 0.
Proof.
  intro q.
  rewrite wedderburn_quaternion_det_equals_norm_sq.
  split.
  - intros Hdet Hn.
    apply Hdet.
    nra.
  - intros Hn Hdet.
    apply Hn.
    nra.
Qed.

(** In the quaternion case, Wedderburn's determinant condition is enough to
    recover a right inverse through Dickson's explicit norm formula. *)
Theorem wedderburn_quaternion_det_implies_right_inverse :
  forall q : CDQuat,
    wedderburn_quaternion_left_det q <> 0 ->
    exists r : CDQuat, quat_mul q r = quat_one.
Proof.
  intros q Hdet.
  exists (quat_inv q).
  apply dickson_quat_right_inverse.
  intro Hn.
  apply Hdet.
  rewrite wedderburn_quaternion_det_equals_norm_sq.
  nra.
Qed.

Theorem wedderburn_quaternion_det_implies_left_inverse :
  forall q : CDQuat,
    wedderburn_quaternion_left_det q <> 0 ->
    exists l : CDQuat, quat_mul l q = quat_one.
Proof.
  intros [a b c d] Hdet.
  exists (quat_inv {| qa := a; qb := b; qc := c; qd := d |}).
  unfold quat_inv, quat_mul, quat_conj, quat_scale, quat_one, quat_norm_sq.
  simpl in *.
  assert (Hn' : a * a + b * b + c * c + d * d <> 0).
  {
    intro Habs.
    apply Hdet.
    rewrite wedderburn_quaternion_det_equals_norm_sq.
    unfold quat_norm_sq in *.
    simpl in *.
    nra.
  }
  repeat f_equal; field; exact Hn'.
Qed.

Theorem wedderburn_quaternion_two_sided_inverse :
  forall q : CDQuat,
    wedderburn_quaternion_left_det q <> 0 ->
    quat_mul q (quat_inv q) = quat_one /\
    quat_mul (quat_inv q) q = quat_one.
Proof.
  intros q Hdet.
  split.
  - apply dickson_quat_right_inverse.
    intro Hn.
    apply Hdet.
    rewrite wedderburn_quaternion_det_equals_norm_sq.
    nra.
  - destruct q as [a b c d].
    unfold quat_inv, quat_mul, quat_conj, quat_scale, quat_one, quat_norm_sq.
    simpl in *.
    assert (Hn' : a * a + b * b + c * c + d * d <> 0).
    {
      intro Habs.
      apply Hdet.
      rewrite wedderburn_quaternion_det_equals_norm_sq.
      unfold quat_norm_sq in *.
      simpl in *.
      nra.
    }
    repeat f_equal; field; exact Hn'.
Qed.

Definition wedderburn_quaternion_primitive_surface :
    WedderburnPrimitiveN2Surface CDQuat :=
  {| wp_cyclic_surface := wedderburn_quaternion_cyclic_surface;
     wp_one := quat_one;
     wp_det := wedderburn_quaternion_left_det;
     wp_norm := quat_norm_sq;
     wp_inv := quat_inv;
     wp_det_norm_sq := wedderburn_quaternion_det_equals_norm_sq;
     wp_det_nonzero_iff_norm_nonzero :=
       wedderburn_quaternion_det_nonzero_iff_norm_nonzero;
     wp_right_inverse := fun z Hz => proj1 (wedderburn_quaternion_two_sided_inverse z Hz);
     wp_left_inverse := fun z Hz => proj2 (wedderburn_quaternion_two_sided_inverse z Hz) |}.

(** Packaged surface for the two main Wedderburn consequences used later:
    cyclic generation in the n=2 quaternion case, and the determinant
    criterion for invertibility. *)
Theorem wedderburn_quaternion_surface_summary :
  quat_mul qi qj = quat_mul qj (quat_conj qi) /\
  quat_mul qj qj = quat_neg quat_one /\
  (qk = quat_mul qi qj /\
   qi = quat_mul qj qk /\
   qj = quat_mul qk qi) /\
  (forall q : CDQuat,
      wedderburn_quaternion_left_det q = (quat_norm_sq q)^2) /\
  (forall q : CDQuat,
      wedderburn_quaternion_left_det q <> 0 <-> quat_norm_sq q <> 0) /\
  (forall q : CDQuat,
      wedderburn_quaternion_left_det q <> 0 ->
      exists r : CDQuat, quat_mul q r = quat_one) /\
  (forall q : CDQuat,
      wedderburn_quaternion_left_det q <> 0 ->
      exists l : CDQuat, quat_mul l q = quat_one).
Proof.
  split.
  - exact wedderburn_quaternion_cyclic_relation.
  - split.
    + exact wedderburn_quaternion_y_square.
    + split.
      * exact wedderburn_quaternion_cyclic_generation.
      * split.
        -- exact wedderburn_quaternion_det_equals_norm_sq.
        -- split.
           ++ exact wedderburn_quaternion_det_nonzero_iff_norm_nonzero.
           ++ split.
              ** exact wedderburn_quaternion_det_implies_right_inverse.
              ** exact wedderburn_quaternion_det_implies_left_inverse.
Qed.

Definition wedderburn_generalized_quaternion_left_det
    (c2 c3 : R) (q : CDQuat) : R :=
  dickson1921_matrix_det4 (dickson1921_param_matrix_entry c2 c3 q).

Definition wedderburn_generalized_quaternion_inv
    (c2 c3 : R) (q : CDQuat) : CDQuat :=
  quat_scale (/ (dickson1921_param_norm c2 c3 q)) (quat_conj q).

(** Wedderburn's cyclic presentation extends from the ordinary quaternion
    case to the generalized quaternion family in Dickson's notation. *)
Theorem wedderburn_generalized_quaternion_cyclic_relation :
  forall c2 c3 : R,
    dickson1921_param_mul c2 c3 qi qj =
    dickson1921_param_mul c2 c3 qj (quat_conj qi).
Proof.
  intros c2 c3.
  unfold dickson1921_param_mul, qi, qj, quat_conj.
  simpl.
  f_equal; ring.
Qed.

Theorem wedderburn_generalized_quaternion_y_square :
  forall c2 c3 : R,
    dickson1921_param_mul c2 c3 qj qj = quat_scale c3 quat_one.
Proof.
  exact dickson1921_param_j_sq.
Qed.

Definition wedderburn_generalized_quaternion_cyclic_surface
    (c2 c3 : R) : WedderburnCyclicN2Surface CDQuat :=
  {| wcy_mul := dickson1921_param_mul c2 c3;
     wcy_theta := quat_conj;
     wcy_x := qi;
     wcy_y := qj;
     wcy_g := quat_scale c3 quat_one;
     wcy_cyclic_relation :=
       wedderburn_generalized_quaternion_cyclic_relation c2 c3;
     wcy_y_square := wedderburn_generalized_quaternion_y_square c2 c3 |}.

Theorem wedderburn_generalized_quaternion_cyclic_generation :
  forall c2 c3 : R,
    c2 <> 0 ->
    c3 <> 0 ->
    qk = dickson1921_param_mul c2 c3 qi qj /\
    qi = quat_scale (- / c3) (dickson1921_param_mul c2 c3 qj qk) /\
    qj = quat_scale (- / c2) (dickson1921_param_mul c2 c3 qk qi).
Proof.
  intros c2 c3 Hc2 Hc3.
  split.
  - symmetry. exact (dickson1921_param_ij c2 c3).
  - split.
    + rewrite dickson1921_param_jk.
      unfold quat_scale, qi.
      simpl.
      repeat f_equal; field; exact Hc3.
    + rewrite dickson1921_param_ki.
      unfold quat_scale, qj.
      simpl.
      repeat f_equal; field; exact Hc2.
Qed.

Theorem wedderburn_generalized_quaternion_det_equals_norm_sq :
  forall c2 c3 : R, forall q : CDQuat,
    wedderburn_generalized_quaternion_left_det c2 c3 q =
    (dickson1921_param_norm c2 c3 q)^2.
Proof.
  exact dickson1921_param_det_equals_norm_sq.
Qed.

Theorem wedderburn_generalized_quaternion_det_nonzero_iff_norm_nonzero :
  forall c2 c3 : R, forall q : CDQuat,
    wedderburn_generalized_quaternion_left_det c2 c3 q <> 0 <->
    dickson1921_param_norm c2 c3 q <> 0.
Proof.
  intros c2 c3 q.
  rewrite wedderburn_generalized_quaternion_det_equals_norm_sq.
  split.
  - intros Hdet Hn.
    apply Hdet.
    nra.
  - intros Hn Hdet.
    apply Hn.
    nra.
Qed.

Theorem wedderburn_generalized_quaternion_right_inverse :
  forall c2 c3 : R, forall q : CDQuat,
    dickson1921_param_norm c2 c3 q <> 0 ->
    dickson1921_param_mul c2 c3 q
      (wedderburn_generalized_quaternion_inv c2 c3 q) = quat_one.
Proof.
  intros c2 c3 [a b c d] Hn.
  unfold dickson1921_param_norm in Hn.
  simpl in Hn.
  assert (Hn' : a * a - c2 * (b * b) - c3 * (c * c) + c2 * c3 * (d * d) <> 0).
  {
    intro Habs.
    apply Hn.
    lra.
  }
  unfold wedderburn_generalized_quaternion_inv, dickson1921_param_mul,
         dickson1921_param_norm, quat_scale, quat_conj, quat_one.
  simpl in *.
  repeat f_equal; field;
  exact Hn'.
Qed.

Theorem wedderburn_generalized_quaternion_det_implies_right_inverse :
  forall c2 c3 : R, forall q : CDQuat,
    wedderburn_generalized_quaternion_left_det c2 c3 q <> 0 ->
    exists r : CDQuat, dickson1921_param_mul c2 c3 q r = quat_one.
Proof.
  intros c2 c3 q Hdet.
  exists (wedderburn_generalized_quaternion_inv c2 c3 q).
  apply wedderburn_generalized_quaternion_right_inverse.
  intro Hn.
  apply Hdet.
  rewrite wedderburn_generalized_quaternion_det_equals_norm_sq.
  nra.
Qed.

Theorem wedderburn_generalized_quaternion_left_inverse :
  forall c2 c3 : R, forall q : CDQuat,
    dickson1921_param_norm c2 c3 q <> 0 ->
    dickson1921_param_mul c2 c3
      (wedderburn_generalized_quaternion_inv c2 c3 q) q = quat_one.
Proof.
  intros c2 c3 [a b c d] Hn.
  unfold dickson1921_param_norm in Hn.
  simpl in Hn.
  assert (Hn' : a * a - c2 * (b * b) - c3 * (c * c) + c2 * c3 * (d * d) <> 0).
  {
    intro Habs.
    apply Hn.
    lra.
  }
  unfold wedderburn_generalized_quaternion_inv, dickson1921_param_mul,
         dickson1921_param_norm, quat_scale, quat_conj, quat_one.
  simpl in *.
  repeat f_equal; field; exact Hn'.
Qed.

Theorem wedderburn_generalized_quaternion_det_implies_left_inverse :
  forall c2 c3 : R, forall q : CDQuat,
    wedderburn_generalized_quaternion_left_det c2 c3 q <> 0 ->
    exists l : CDQuat, dickson1921_param_mul c2 c3 l q = quat_one.
Proof.
  intros c2 c3 q Hdet.
  exists (wedderburn_generalized_quaternion_inv c2 c3 q).
  apply wedderburn_generalized_quaternion_left_inverse.
  intro Hn.
  apply Hdet.
  rewrite wedderburn_generalized_quaternion_det_equals_norm_sq.
  nra.
Qed.

Theorem wedderburn_generalized_quaternion_two_sided_inverse :
  forall c2 c3 : R, forall q : CDQuat,
    wedderburn_generalized_quaternion_left_det c2 c3 q <> 0 ->
    dickson1921_param_mul c2 c3 q
      (wedderburn_generalized_quaternion_inv c2 c3 q) = quat_one /\
    dickson1921_param_mul c2 c3
      (wedderburn_generalized_quaternion_inv c2 c3 q) q = quat_one.
Proof.
  intros c2 c3 q Hdet.
  split.
  - apply wedderburn_generalized_quaternion_right_inverse.
    intro Hn.
    apply Hdet.
    rewrite wedderburn_generalized_quaternion_det_equals_norm_sq.
    nra.
  - apply wedderburn_generalized_quaternion_left_inverse.
    intro Hn.
    apply Hdet.
    rewrite wedderburn_generalized_quaternion_det_equals_norm_sq.
    nra.
Qed.

Definition wedderburn_generalized_quaternion_primitive_surface
