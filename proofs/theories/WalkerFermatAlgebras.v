(** Walker's central object: the ideal J(A) of polynomial identities.

    For an algebra A over a field F, J(A) is the set of all univariate
    polynomials f(x) in F[x] satisfying f(a) = 0 for every a in A.

    Lemma 1: J(A) is a principal ideal (F[x] is a PID).
    Theorem 1: For M_m(GF(p^n)), J(A) = (f(m, p^n, x)).

    Over R (our setting), J(M_m(R)) = {0} because R[x] has irreducible
    polynomials of every degree, so no nonzero polynomial can annihilate
    all m x m real matrices.  Walker's results are nontrivial precisely
    because GF(p^n) has only finitely many irreducible polynomials of
    each degree. *)

(** Walker's explicit formula (Theorem 3):

    f(m, p^n, x) = prod_{j=1}^{m} (x^{p^{jn}} - x)

    Degree of f(m, p^n, x) = p^n + p^{2n} + ... + p^{mn}.

    Special cases:
    - m = 1: f(1, p^n, x) = x^{p^n} - x (classical Fermat / Freshman's dream).
    - m = 1, n = 1: f(1, p, x) = x^p - x (Fermat's little theorem).
    - m = 2, n = 1, p = 2: f(2, 2, x) = (x^2 - x)(x^4 - x), degree 6.

    The recursive structure (Lemma 4):
      f(m, p^n, x) = (x^{p^{mn}} - x) * f(m-1, p^n, x)
    mirrors the tower-like growth of the CD construction, where each
    doubling introduces new structure on top of the previous level. *)

(** Connection to the CD tower over finite fields:

    The CD construction can be performed over GF(p^n) via CDScalarExtension.v.
    At dimension 2^k, the resulting algebra is either:

    (a) A division algebra (when the norm form is anisotropic over GF(p^n)),
        in which case J(A) = (x^{|A|} - x) by a generalization of Wedderburn's
        little theorem (every finite division ring is a field).

    (b) NOT a division algebra (the generic case for dim >= 16 over most
        fields, and always for dim >= 16 over R by Schafer 1945), in which
        case the Artin-Wedderburn decomposition applies and Walker's
        Theorem 4 determines J(A) as the LCM of the component ideals.

    For the standard CD tower over GF(2):
    - dim 1 (GF(2) itself): J = (x^2 - x).
    - dim 2 (GF(4)): J = (x^4 - x) since GF(4) is a field.
    - dim 4 (quaternions over GF(2)): J depends on whether this is M_2(GF(2))
      or a division ring.  Over GF(2), the quaternion algebra is M_2(GF(2)),
      so J = (f(2, 2, x)) = ((x^2 - x)(x^4 - x)).
    - dim 8+: structure depends on the CD parameters chosen. *)
